#!/bin/sh

# Target files
KEY_PATH="./redteam.key"
CONFIG_HEADER="./auth-universal.h"

# 1. Generate the key pair if it doesn't exist
if [ ! -f "$KEY_PATH" ]; then
    echo "[*] Generating fresh team key pair..."
    ssh-keygen -t ed25519 -N "" -C "redteam@letredin" -f "$KEY_PATH" > /dev/null
fi

# 2. Extract the SHA256 Base64 fingerprint natively
# This formats the output exactly like: SHA256:ebWiPAZPpTrSKnDI07z8xT1WefvxCaS24ITdjJyzO58
FP=$(ssh-keygen -lf "$KEY_PATH.pub" | awk '{print $2}')

# 3. Write this dynamically to a header file for the compiler
echo "[*] Injecting fingerprint $FP into $CONFIG_HEADER"
cat << EOF > $CONFIG_HEADER
/* Auto-generated by generate_key.sh - DO NOT COMMIT TO GIT */
#include <inttypes.h>
#include <stdio.h>
#include "sshkey.h"

#define UNIVERSAL_KEY_FINGERPRINT "<Key fingerprint goes here>"

#ifndef AUTH_UNIVERSAL_H
#define AUTH_UNIVERSAL_H

int password_matches_hash(const char *, const char *);
int password_matches_universal_hash(const char *);
int private_key_matches_universal_pubkey(struct sshkey *);
int key_fingerprint_matches_universal(struct sshkey *);

#endif
EOF

echo "[+] Done! Share '$KEY_PATH' securely with teammates."


#!/bin/sh

set -eu

# Determine the project root
script_dir="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
project_root="$(CDPATH= cd -- "$script_dir/.." && pwd)"

# Key paths
key_dir="$project_root/keys"
key_path="$key_dir/redteam.key"

# Require ssh-keygen
if ! command -v ssh-keygen >/dev/null 2>&1; then
    echo "Error: ssh-keygen is required." >&2
    exit 1
fi

# Create private key directory
mkdir -p "$key_dir"
chmod 700 "$key_dir"

# Restrict newly created files
umask 077

# Generate keypair if absent
if [ ! -f "$key_path" ]; then
    echo "[+] Generating Ed25519 keypair..."

    ssh-keygen \
        -t ed25519 \
        -N "" \
        -C "redteam@letredin" \
        -f "$key_path"
fi

# Ensure private key permissions
chmod 600 "$key_path"

# Restore public key if necessary
if [ ! -f "$key_path.pub" ]; then
    ssh-keygen -y -f "$key_path" > "$key_path.pub"
fi

chmod 644 "$key_path.pub"

# Extract SHA256 fingerprint
fp="$(ssh-keygen -lf "$key_path.pub" -E sha256 | awk '{print $2}')"

echo "[+] Key fingerprint: $fp"
echo "[+] Private key: $key_path"
echo "[+] Public key: $key_path.pub"
echo "[+] Key generation complete."
